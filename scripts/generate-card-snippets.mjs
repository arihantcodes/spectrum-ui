import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(projectRoot, 'components', 'spectrumui', 'cards.tsx');
const outputPath = path.join(projectRoot, 'components', 'spectrumui', 'cards.source.ts');

// Each card in cards.tsx is a top-level `export function <Name>Card()` declaration that
// closes with a brace in column zero. Capturing that span keeps the copy-paste snippet
// byte-identical to the component that is actually rendered, so the two cannot drift.
function extractCards(source) {
  const lines = source.split('\n');
  const cards = [];
  let current = null;

  for (const line of lines) {
    const start = line.match(/^export function (\w+Card)\(\) \{$/);
    if (start) {
      current = { name: start[1], body: [line.replace(/^export /, '')] };
      continue;
    }
    if (!current) continue;

    current.body.push(line);
    if (line === '}') {
      cards.push({ name: current.name, code: current.body.join('\n') });
      current = null;
    }
  }

  if (current) {
    throw new Error(`Unterminated card declaration: ${current.name}`);
  }
  return cards;
}

const cards = extractCards(readFileSync(sourcePath, 'utf8'));

if (cards.length === 0) {
  console.error(`No card components found in ${path.relative(projectRoot, sourcePath)}`);
  process.exit(1);
}

const duplicates = cards
  .map((card) => card.name)
  .filter((name, index, all) => all.indexOf(name) !== index);
if (duplicates.length > 0) {
  console.error(`Duplicate card names: ${duplicates.join(', ')}`);
  process.exit(1);
}

const entries = cards.map((card) => `  ${card.name}: ${JSON.stringify(card.code)},`).join('\n');

const output = `// Generated by scripts/generate-card-snippets.mjs — do not edit by hand.
// Run \`npm run generate:card-snippets\` after changing components/spectrumui/cards.tsx.

export const CARD_SOURCE: Record<string, string> = {
${entries}
};
`;

if (process.argv.includes('--write')) {
  writeFileSync(outputPath, output);
  console.log(`Generated ${path.relative(projectRoot, outputPath)} for ${cards.length} cards`);
} else if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== output) {
    console.error(`Stale generated file: ${path.relative(projectRoot, outputPath)}`);
    process.exit(1);
  }
  console.log(`Card snippets are current for ${cards.length} cards`);
} else {
  console.error('Usage: node scripts/generate-card-snippets.mjs --write | --check');
  process.exit(1);
}
