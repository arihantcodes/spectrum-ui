import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const footersDir = path.join(projectRoot, "components", "spectrumui", "footers")
const catalogPath = path.join(footersDir, "catalog.ts")
const outputPath = path.join(footersDir, "footers.source.ts")

const catalogSource = readFileSync(catalogPath, "utf8")
const names = [...catalogSource.matchAll(/componentName:\s*"(\w+)"/g)].map((match) => match[1])
const files = [...catalogSource.matchAll(/fileName:\s*"([^"]+)"/g)].map((match) => match[1])

if (names.length !== files.length || names.length === 0) {
  console.error("Could not parse FOOTER_CATALOG component names and files")
  process.exit(1)
}

const entries = names.map((name, index) => {
  const filePath = path.join(footersDir, files[index])
  if (!existsSync(filePath)) {
    throw new Error(`Missing footer source: ${files[index]}`)
  }
  return `  ${name}: ${JSON.stringify(readFileSync(filePath, "utf8"))},`
})

const output = `// Generated by scripts/generate-footer-snippets.mjs — do not edit by hand.

export const FOOTER_SOURCE: Record<string, string> = {
${entries.join("\n")}
};
`

if (process.argv.includes("--write")) {
  writeFileSync(outputPath, output)
  console.log(`Generated ${path.relative(projectRoot, outputPath)} for ${names.length} footers`)
} else if (process.argv.includes("--check")) {
  if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== output) {
    console.error(`Stale generated file: ${path.relative(projectRoot, outputPath)}`)
    process.exit(1)
  }
  console.log(`Footer snippets are current for ${names.length} footers`)
} else {
  console.error("Usage: node scripts/generate-footer-snippets.mjs --write | --check")
  process.exit(1)
}
